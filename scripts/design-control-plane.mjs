#!/usr/bin/env node
// The GABF Analysis design control plane, generated and checked with the agent-graph engine.
//
//   node scripts/design-control-plane.mjs generate   write tokens, screens, the prototype, tickets
//   node scripts/design-control-plane.mjs check      fail when anything on disk disagrees
//   node scripts/design-control-plane.mjs impact <node-id> [node-id...]
//
// Why this script and not the engine's own command lines: build-screens.mjs, build-prototype.mjs,
// and design-graph.mjs ignore --root on their command lines and act on agent-graph's own tree
// (only design-feedback.mjs reads --root). Their exported functions all take a root, so this
// script imports them read only and passes this repository. Two things are adapted here rather than
// forked there. Screens: the engine's screen renderer draws agent-graph's five surfaces with
// illustrative bodies; a GABF screen is the built page itself, so each screen here is its surface's
// sketch (a live frame) driven into the state the manifest declares. The prototype shell: the
// engine's page is used as generated, with its agent-graph wording replaced by exact, counted
// substitutions, so an upstream change to that wording fails the check instead of slipping through.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ROOT } from './lib/paths.mjs';
import { engine } from './lib/agent-graph.mjs';
import { renderTicketFiles, sealIssues } from './lib/review-store.mjs';

const D = (p) => resolve(ROOT, 'docs/design', p);
const SCREENS_DIR = 'prototype/screens';
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// ---------- tokens, published from the site stylesheet ----------
function propertiesIn(block) {
  const out = {};
  for (const m of block.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}
export function tokensFromCss(css) {
  const light = /^:root\s*\{([\s\S]*?)\n\}/m.exec(css);
  if (!light) throw new Error('site/assets/styles.css: the :root block was not found');
  return {
    'schema-version': 1,
    status: 'PUBLISHED',
    source: 'site/assets/styles.css',
    note: 'Generated by scripts/design-control-plane.mjs from the custom properties in site/assets/styles.css: the :root block is the light scheme. Nothing here is set by hand; change the stylesheet and regenerate. Type sizes, spacing, and radii are literal values in the stylesheet rather than custom properties, so they are not published as tokens.',
    schemes: { light: propertiesIn(light[1]) },
  };
}
const SHELL_ALIASES = `/* Shell aliases: the engine's prototype page is styled with its own variable names. Each is
   pointed at a site token above, or at a literal the site stylesheet itself uses (the system font
   stack, the code font stack, 1px rules, 6px and 3px radii). Shadows and transitions are left
   undefined because the site has none to publish. */
:root {
  --bg-primary: var(--page);
  --bg-surface: var(--card);
  --bg-surface-hover: var(--surface-1);
  --bg-inset: var(--surface-1);
  --border-default: var(--control-border);
  --border-muted: var(--border);
  --accent-blue: var(--link);
  --accent-green: var(--good);
  --accent-amber: var(--warn);
  --accent-red: var(--series-8);
  --accent-purple: var(--series-7);
  --accent-teal: var(--series-3);
  --focus-ring: 2px solid var(--focus);
  --font-sans: system-ui, -apple-system, "Segoe UI", sans-serif;
  --font-mono: ui-monospace, SFMono-Regular, Menlo, monospace;
  --border-width: 1px;
  --radius-md: 6px;
  --radius-sm: 3px;
}
`;
export function tokensCss(css) {
  const blocks = [/^:root\s*\{[\s\S]*?\n\}/m]
    .map((re) => { const m = re.exec(css); if (!m) throw new Error('site/assets/styles.css: a token block was not found'); return m[0]; });
  return `/* Generated by scripts/design-control-plane.mjs. Do not edit by hand.
   The site's custom properties, copied verbatim from site/assets/styles.css. */
${blocks.join('\n')}

${SHELL_ALIASES}`;
}

// ---------- screens: each is its surface's sketch, driven into one state ----------
export function stateUrl(surface, state) {
  const route = state.route || surface.route;
  return `/${state.served || 'site'}${route}${state.hash || ''}`;
}

function sketchParts(file, surfaceName, route) {
  const html = readFileSync(D(`sketches/${file}`), 'utf8');
  const head = /<head>([\s\S]*?)<\/head>/.exec(html);
  const label = /<span class="dcp-crumbs">([^<]+)<\/span>/.exec(html);
  const frame = /<iframe class="dcp-live-frame" title="([^"]+)" src="([^"]+)"><\/iframe>/.exec(html);
  if (!head || !label || !frame) throw new Error(`sketches/${file} does not have the head, the dcp-crumbs label, and the dcp-live-frame iframe a screen is composed from`);
  if (frame[2] !== `/site${route}`) throw new Error(`sketches/${file} frames ${frame[2]} but the manifest gives surface ${surfaceName} the route ${route}`);
  return { head: head[1], label: label[1], frameTitle: frame[1] };
}

function actionsHtml(options) {
  return options.map((a) => (a.target
    ? `<a class="action" href="${a.target}.html" data-target="${a.target}">${esc(a.label)}</a>`
    : a.stays
      ? `<button class="action in-place" type="button" data-action="${esc(a.label)}">${esc(a.label)}</button>`
      : `<button class="action unmapped" type="button" data-action="${esc(a.label)}">${esc(a.label)}</button>`)).join('');
}

function renderScreen(screen, node, surfaceName, surface, options) {
  const parts = sketchParts(surface.sketch, surfaceName, surface.route);
  const state = node.state || {};
  const url = stateUrl(surface, state);
  const head = parts.head.replace(/<title>[^<]*<\/title>/, `<title>${esc(screen.id)} ${esc(screen.name)}</title>`);
  return `<!doctype html>
<html lang="en">
<head>${head}<script src="screen.js" defer></script>
</head>
<body data-screen="${esc(screen.id)}" data-path="${esc(node.path)}" data-surface="${esc(surfaceName)}" data-frame="${esc(state.frame || 'desktop')}" data-live="${esc(url)}" data-drive="${esc(state.drive || '')}">
<header class="dcp-bar"><span class="dcp-crumbs">${esc(parts.label)}<span class="sep">/</span>${esc(screen.id)} ${esc(screen.name.replace(/-/g, ' '))}</span><span class="dcp-state" data-path="${esc(node.path)}">${esc(node.path)} path${state.frame === 'phone' ? ', 390 px frame' : ''}</span><a class="dcp-url" href="${esc(url)}" target="_blank" rel="noopener">${esc(url)}</a>
<div class="dcp-actions" aria-label="What the reader can do">${actionsHtml(options)}</div>
<p class="dcp-note" hidden></p></header>
<main class="dcp-stage"><iframe class="dcp-live-frame" title="${esc(parts.frameTitle)}, ${esc(screen.id)}"></iframe></main>
</body>
</html>
`;
}

// The page script every screen shares. It clears the stored filter (the hash is then the whole
// state), loads the live page, runs the drive step, and reports clicks to the prototype shell.
const SCREEN_JS = `// Generated by scripts/design-control-plane.mjs. Do not edit by hand.
(function () {
  var body = document.body;
  var frame = document.querySelector('.dcp-live-frame');
  var note = document.querySelector('.dcp-note');
  var inShell = window.parent !== window;
  function tell(kind, detail) { if (inShell) window.parent.postMessage(Object.assign({ source: 'agent-graph-screen', kind: kind }, detail), '*'); }
  function say(text) { note.textContent = text; note.hidden = false; }
  try { localStorage.removeItem('gabf-filters'); } catch (e) { /* storage unavailable: the hash still carries the state */ }
  function waitFor(find, ms) {
    return new Promise(function (resolve) {
      var start = Date.now();
      (function poll() {
        var hit = null;
        try { hit = find(); } catch (e) { hit = null; }
        if (hit || Date.now() - start > ms) resolve(hit); else setTimeout(poll, 100);
      })();
    });
  }
  function visible(el) { var r = el.getBoundingClientRect(); return r.width > 0 && r.height > 0; }
  var DRIVES = {
    'filters-open': function (doc) {
      return waitFor(function () { return doc.querySelector('.filter-trigger'); }, 8000).then(function (b) {
        if (!b) { say('This state opens the Filters panel, and this page has no Filters button.'); return; }
        b.click();
        return waitFor(function () { return doc.querySelector('dialog.filter-panel[open]'); }, 4000);
      });
    },
    'estimate-open': function (doc) {
      return waitFor(function () { return Array.prototype.find.call(doc.querySelectorAll('.est-mark'), visible); }, 15000).then(function (b) {
        if (!b) { say('This state opens an estimate note, and this page shows no (E) mark in this build.'); return; }
        b.scrollIntoView({ block: 'center' });
        b.click();
        return waitFor(function () { var p = doc.getElementById('est-popover'); return p && !p.hidden && p.textContent.indexOf('Loading') === -1 ? p : null; }, 6000);
      });
    },
  };
  frame.addEventListener('load', function () {
    var drive = DRIVES[body.dataset.drive];
    var doc = null;
    try { doc = frame.contentDocument; } catch (e) { doc = null; }
    var done = drive && doc ? drive(doc) : Promise.resolve();
    Promise.resolve(done).then(function () { setTimeout(function () { body.dataset.ready = 'true'; tell('ready', { screen: body.dataset.screen }); }, 600); });
  }, { once: true });
  frame.src = body.dataset.live;
  document.addEventListener('click', function (event) {
    var link = event.target.closest('a[data-target]');
    if (link && inShell) { event.preventDefault(); tell('navigate', { screen: link.dataset.target, via: link.textContent.trim() }); return; }
    var dead = event.target.closest('.unmapped');
    if (dead) { event.preventDefault(); tell('unmapped', { screen: body.dataset.screen, action: dead.dataset.action }); }
  });
})();
`;

// ---------- the prototype shell, with its agent-graph wording replaced ----------
function substitutions(screenCount, jobCount) {
  return [
    ['<title>agent-graph journeys</title>', '<title>GABF Analysis design review</title>'],
    ['<span class="brand">agent-graph journeys</span>', '<span class="brand">GABF Analysis design review</span>'],
    ['<h1>Thirty five screens, five jobs</h1>', `<h1>${screenCount} screens of the live site, ${jobCount} jobs</h1>`],
    [/<p class="lede">Organised by the jobs[\s\S]*?<\/p>/, '<p class="lede">Every screen is the built site, driven into one state through its own route, URL hash, or the way the review server serves its data. Organised by the jobs in PRODUCT.md. Choose a job to walk its screens. Explain says why a screen exists and what it is made of; Feedback records a note on the screen, and the Feedback button inside the page pins a note to a spot.</p>'],
    ["'The banner should name the project, not just the file count.'", "'Say what should change on this screen.'"],
    ['Start it with: npm run design:serve', 'Start it with: npm run review'],
  ];
}
function applySubstitutions(html, subs) {
  for (const [from, to] of subs) {
    const count = typeof from === 'string' ? html.split(from).length - 1 : (html.match(new RegExp(from.source, 'g')) || []).length;
    if (count !== 1) throw new Error(`the engine's prototype page no longer matches the substitution for ${String(from).slice(0, 60)} (found ${count}); update scripts/design-control-plane.mjs`);
    html = html.replace(from, to);
  }
  return html;
}

// ---------- everything, in memory ----------
export async function renderAll() {
  const graph = await engine('design-graph.mjs');
  const spec = await engine('spec-screens.mjs');
  const screensLib = await engine('build-screens.mjs');
  const proto = await engine('build-prototype.mjs');
  const fb = await engine('design-feedback.mjs');

  const css = readFileSync(resolve(ROOT, 'site/assets/styles.css'), 'utf8');
  const files = new Map();
  files.set('tokens.json', `${JSON.stringify(tokensFromCss(css), null, 2)}\n`);
  files.set('sketches/tokens.css', tokensCss(css));

  // The graph synthesizes token nodes from tokens.json on disk; generate writes it first.
  const { nodes, manifest } = graph.loadGraph(ROOT);
  const screens = spec.parseSpec(ROOT);
  const byId = Object.fromEntries(screens.map((s) => [s.id, s]));
  for (const screen of screens) {
    const node = nodes[`screen:${screen.id}`];
    if (!node) continue;
    const surface = graph.surfaceOf(nodes, `screen:${screen.id}`);
    if (!surface) continue;
    const declared = manifest.surfaces[surface.name];
    files.set(`${SCREENS_DIR}/${screen.id}.html`, renderScreen(screen, node, surface.name, declared, screensLib.matchActions(screen, byId)));
  }
  files.set(`${SCREENS_DIR}/screen.js`, SCREEN_JS);
  const jobs = Object.values(nodes).filter((n) => n.kind === 'journey').length;
  files.set('prototype/index.html', applySubstitutions(proto.renderHtml(ROOT), substitutions(screens.length, jobs)));
  for (const [name, body] of renderTicketFiles(fb.readFeedback(ROOT))) files.set(`../work-items/${name}`, body);
  return { files, graph, spec, screensLib, fb, nodes, manifest, screens };
}

function writeIfChanged(path, body) {
  if (existsSync(path) && readFileSync(path, 'utf8') === body) return;
  mkdirSync(resolve(path, '..'), { recursive: true });
  writeFileSync(path, body);
}

export async function generate() {
  writeIfChanged(D('tokens.json'), `${JSON.stringify(tokensFromCss(readFileSync(resolve(ROOT, 'site/assets/styles.css'), 'utf8')), null, 2)}\n`);
  const { files } = await renderAll();
  if (existsSync(D(SCREENS_DIR))) rmSync(D(SCREENS_DIR), { recursive: true });
  for (const [name, body] of files) writeIfChanged(D(name), body);
  const tickets = resolve(ROOT, 'docs/work-items');
  if (existsSync(tickets)) for (const f of readdirSync(tickets)) if (!files.has(`../work-items/${f}`)) rmSync(resolve(tickets, f));
  return files;
}

export async function issues() {
  const out = [];
  let r;
  try { r = await renderAll(); } catch (e) { return [e.message]; }
  const { files, graph, spec, screensLib, fb, nodes, manifest, screens } = r;
  out.push(...graph.graphIssues(nodes), ...graph.flagIssues(nodes, graph.loadGraph(ROOT).flags), ...graph.logIssues(graph.readLog(ROOT)));
  out.push(...spec.specIssues(screens, nodes));
  const byId = Object.fromEntries(screens.map((s) => [s.id, s]));
  for (const s of screens) {
    for (const m of screensLib.matchActions(s, byId)) if (!m.target && !m.stays) out.push(`${s.id}: the action "${m.label}" has no destination and is not declared to stay`);
    for (const t of s.goesTo) if (!screensLib.matchActions(s, byId).some((m) => m.target === t)) out.push(`${s.id} names ${t} but no control reaches it`);
  }
  for (const [name, surface] of Object.entries(manifest.surfaces)) {
    if (!surface.route) out.push(`surface ${name} has no route`);
    if (!surface.sketch || !existsSync(D(`sketches/${surface.sketch}`))) out.push(`surface ${name} has no sketch file`);
  }
  for (const [id, node] of Object.entries(nodes)) if (node.kind === 'screen' && !node.state) out.push(`${id} declares no state, so nothing can drive the live page into it`);
  for (const [name, body] of files) {
    const path = D(name);
    if (!existsSync(path)) out.push(`docs/design/${name} is missing. Run: npm run design:build`);
    else if (readFileSync(path, 'utf8') !== body) out.push(`docs/design/${name} is stale. Run: npm run design:build`);
  }
  if (existsSync(D(SCREENS_DIR))) for (const f of readdirSync(D(SCREENS_DIR))) if (!files.has(`${SCREENS_DIR}/${f}`)) out.push(`docs/design/${SCREENS_DIR}/${f} is not generated by the manifest and should be removed`);
  const tickets = resolve(ROOT, 'docs/work-items');
  if (existsSync(tickets)) for (const f of readdirSync(tickets)) if (!files.has(`../work-items/${f}`)) out.push(`docs/work-items/${f} has no feedback note behind it`);
  const records = fb.readFeedback(ROOT);
  out.push(...fb.feedbackIssues(records), ...sealIssues(records));
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [command = 'check', ...rest] = process.argv.slice(2);
  if (command === 'generate') {
    const files = await generate();
    const screens = [...files.keys()].filter((k) => /screens\/S-\d+\.html$/.test(k)).length;
    console.log(`Design control plane generated: tokens, ${screens} screens, the prototype, and ${[...files.keys()].filter((k) => k.startsWith('../work-items/WI-')).length} tickets.`);
  } else if (command === 'check') {
    const found = await issues();
    if (found.length) { for (const i of found) console.error(i); console.error(`\nDesign control plane FAIL: ${found.length} issue(s).`); process.exit(1); }
    console.log('Design control plane PASS: graph, spec, tokens, screens, prototype, feedback chain and seals, and tickets agree.');
  } else if (command === 'impact') {
    const graph = await engine('design-graph.mjs');
    const { nodes } = graph.loadGraph(ROOT);
    const unknown = rest.filter((id) => !nodes[id]);
    if (!rest.length || unknown.length) { console.error(rest.length ? `unknown node(s): ${unknown.join(', ')}` : 'usage: design-control-plane.mjs impact <node-id> [node-id...]'); process.exit(2); }
    for (const r of graph.impact(nodes, rest)) console.log(`depth ${r.depth}  ${(nodes[r.node]?.kind ?? '').padEnd(9)} ${r.node}`);
  } else {
    console.error(`unknown command ${command}; expected generate, check, or impact`);
    process.exit(2);
  }
}
